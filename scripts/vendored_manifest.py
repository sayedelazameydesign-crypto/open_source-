#!/usr/bin/env python3
"""Vendored-snapshot integrity manifest.

The platform hosts one third-party tree verbatim — ``packages/craft-launcher``
(ADR-0015). Hosting it *unmodified* is not a house style, it is the legal
precondition: the ArtCraft trademark permission in
``packages/craft-launcher/docs/brand/LICENSE-brand.txt`` covers the marks only
"as part of copies of this repository", and it "ends automatically for anyone
who breaks these terms". The moment a single file inside that tree diverges
from upstream, the tree becomes a *modified version* and the marks must be
removed from it.

Divergence used to be guarded only by prose. This script makes it mechanical:
every tracked file in the tree is recorded with a sha256 in
``docs/vendored/craft-launcher.sha256``; ``tests/test_vendored_integrity.py``
verifies that manifest offline on every test run, and CI can additionally
re-derive it from the upstream tarball at the pinned commit.

Usage
-----
    python scripts/vendored_manifest.py verify              # offline (default)
    python scripts/vendored_manifest.py verify --upstream   # also compare to upstream
    python scripts/vendored_manifest.py write --commit SHA [--version V]

Exit status is 0 when the tree matches, 1 on any drift, 2 on misuse. Network
is used *only* with ``--upstream``; the default path is offline so the test
suite keeps its "no network" contract.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import re
import subprocess
import sys
import tarfile
import urllib.request
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

# ---------------------------------------------------------------------------
# What is pinned. Kept here (not only in the manifest) so `write` can be run
# without arguments after a deliberate snapshot refresh, and so the test suite
# has a single importable source of truth.
# ---------------------------------------------------------------------------

TREE = "packages/craft-launcher"
MANIFEST = "docs/vendored/craft-launcher.sha256"
SOURCE = "https://github.com/storytold/craft-launcher"
COMMIT = "0f295d4b9c90d15c2e38e36c322bdbc0fa943a54"
VERSION = "0.4.1"

_HEADER = """\
# ArtCraft Launcher — vendored snapshot integrity manifest
#
# Generated by scripts/vendored_manifest.py. DO NOT EDIT BY HAND.
#
# Every git-tracked file under `{tree}` with its sha256, plus one aggregate
# `digest` over the sorted records. Verified offline on every test run by
# tests/test_vendored_integrity.py; re-derived from the upstream tarball in
# .github/workflows/launcher-ci.yml.
#
# Why this exists: hosting this tree is permitted *because* it is an unmodified
# copy of the upstream repository. The ArtCraft marks inside it are NOT open
# source (see {tree}/docs/brand/LICENSE-brand.txt) and that permission ends
# automatically if the copy is modified without the marks being removed.
# So: never hand-edit anything under {tree}. Propose the change upstream,
# refresh the snapshot, then regenerate this file.
#
#   docs/VENDORED-craft-launcher.md — hosting terms and refresh procedure
#   docs/THIRD_PARTY_POLICY.md      — the repository-wide rules (rule T-3)
"""

_KEY_RE = re.compile(r"^(?P<key>[a-z]+)\s+(?P<value>.*)$")


@dataclass(frozen=True)
class Manifest:
    source: str
    commit: str
    version: str
    tree: str
    digest: str
    records: dict[str, str]  # relpath -> sha256
    declared_files: int = -1  # the `files` header value, cross-checked against records

    @property
    def files(self) -> int:
        return len(self.records)


def repo_root(start: Path | None = None) -> Path:
    """Locate the repository root, preferring git so worktrees behave."""
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--show-toplevel"],
            cwd=start or Path.cwd(),
            capture_output=True,
            text=True,
            check=True,
        )
        return Path(out.stdout.strip())
    except (subprocess.CalledProcessError, FileNotFoundError):
        # Not a git checkout (e.g. an unpacked sdist): walk up for a marker.
        here = (start or Path.cwd()).resolve()
        for candidate in (here, *here.parents):
            if (candidate / "pyproject.toml").exists() and (candidate / TREE).exists():
                return candidate
        raise SystemExit(f"could not locate the repository root from {here}") from None


def _git_ls_files(root: Path, tree: str, *flags: str) -> list[str]:
    """Tracked (or dirty-untracked) paths under `tree`, relative to it.

    "Tracked" is the right scope for a compliance check: it is exactly what a
    clone of this repository — and therefore what a distribution of it — contains.
    Build output and local debris are excluded by .gitignore and are reported
    separately by :func:`untracked_files`.
    """
    cmd = ["git", "ls-files", "-z", *flags, "--", tree]
    try:
        out = subprocess.run(cmd, cwd=root, capture_output=True, text=True, check=True)
    except FileNotFoundError as exc:  # git not installed
        raise SystemExit(f"git is required to check {tree}: {exc}") from None
    except subprocess.CalledProcessError as exc:
        raise SystemExit(f"`{' '.join(cmd)}` failed in {root}: {exc.stderr.strip()}") from exc
    paths = [p for p in out.stdout.split("\0") if p]
    prefix = f"{tree}/"
    return sorted(p[len(prefix) :] if p.startswith(prefix) else p for p in paths)


def tracked_files(root: Path, tree: str = TREE) -> list[str]:
    """Files a clone of this repository would contain under `tree`."""
    return _git_ls_files(root, tree)


def untracked_files(root: Path, tree: str = TREE) -> list[str]:
    """Present on disk, not ignored, not committed — a dirty working tree."""
    return _git_ls_files(root, tree, "--others", "--exclude-standard")


def _digest_stream(read: Callable[[int], bytes]) -> str:
    """sha256 of a byte stream, chunked so a 1 GB asset does not get slurped.

    Takes a *bound* read method rather than a file object: binding at the call
    site keeps the lambda below free of loop variables (ruff B023) and lets the
    same helper serve both a local file and a tar member.
    """
    digest = hashlib.sha256()
    for chunk in iter(lambda: read(1 << 20), b""):
        digest.update(chunk)
    return digest.hexdigest()


def sha256_file(path: Path) -> str:
    with path.open("rb") as handle:
        return _digest_stream(handle.read)


def collect(root: Path, tree: str = TREE) -> dict[str, str]:
    """Hash every tracked file under `tree`, keyed by its tree-relative path."""
    base = root / tree
    records: dict[str, str] = {}
    for rel in tracked_files(root, tree):
        path = base / rel
        if path.is_symlink():
            # Record the link itself, not its target: a snapshot that swaps a
            # symlink for a regular file is a modification even if the bytes
            # the target holds are unchanged.
            records[rel] = f"symlink:{path.readlink()}"
        elif not path.exists():
            records[rel] = "missing"
        else:
            records[rel] = sha256_file(path)
    return records


def aggregate(records: dict[str, str]) -> str:
    """One digest over the whole tree, order-independent."""
    body = "".join(f"{records[k]}  {k}\n" for k in sorted(records))
    return f"sha256:{hashlib.sha256(body.encode('utf-8')).hexdigest()}"


# ---------------------------------------------------------------------------
# Manifest I/O
# ---------------------------------------------------------------------------


def render(records: dict[str, str], *, source: str, commit: str, version: str, tree: str) -> str:
    out = io.StringIO()
    out.write(_HEADER.format(tree=tree))
    out.write(f"source      {source}\n")
    out.write(f"commit      {commit}\n")
    out.write(f"version     {version}\n")
    out.write(f"tree        {tree}\n")
    out.write(f"files       {len(records)}\n")
    out.write(f"digest      {aggregate(records)}\n")
    out.write("#\n")
    out.write("# ---- per-file records (sorted, `<sha256>  <path>`) ----\n")
    for rel in sorted(records):
        out.write(f"{records[rel]}  {rel}\n")
    return out.getvalue()


def parse(path: Path) -> Manifest:
    keys: dict[str, str] = {}
    records: dict[str, str] = {}
    in_body = False
    for lineno, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.rstrip()
        if not line:
            continue
        if line.startswith("# ----"):
            in_body = True
            continue
        if line.startswith("#"):
            continue
        if not in_body:
            match = _KEY_RE.match(line)
            if match:
                keys[match["key"]] = match["value"].strip()
            continue
        digest, _, rel = line.partition("  ")
        if not rel:
            raise SystemExit(f"{path}:{lineno}: malformed record {raw!r}")
        records[rel.strip()] = digest.strip()

    missing = {"source", "commit", "version", "tree", "digest"} - keys.keys()
    if missing:
        raise SystemExit(f"{path}: manifest is missing key(s): {', '.join(sorted(missing))}")
    declared = keys.get("files", "").strip()
    return Manifest(
        source=keys["source"],
        commit=keys["commit"],
        version=keys["version"],
        tree=keys["tree"],
        digest=keys["digest"],
        records=records,
        declared_files=int(declared) if declared.isdigit() else -1,
    )


# ---------------------------------------------------------------------------
# Upstream re-derivation (network; CI only)
# ---------------------------------------------------------------------------


def upstream_records(commit: str, tree: str = TREE) -> dict[str, str]:
    """Hash the upstream tarball at `commit` so it can be compared to ours.

    Uses only the standard library — the toolchain must not grow a dependency
    for a compliance check.
    """
    owner_repo = SOURCE.removeprefix("https://github.com/")
    url = f"https://codeload.github.com/{owner_repo}/tar.gz/{commit}"
    request = urllib.request.Request(url, headers={"User-Agent": "vendored-manifest/1.0"})
    # The URL is built from a hardcoded https host and a validated 40-hex commit,
    # never from input; there is no scheme or host for a caller to steer.
    with urllib.request.urlopen(request, timeout=120) as response:
        blob = response.read()

    records: dict[str, str] = {}
    with tarfile.open(fileobj=io.BytesIO(blob), mode="r:gz") as archive:
        members = [m for m in archive.getmembers() if m.isfile() or m.issym()]
        if not members:
            raise SystemExit(f"upstream tarball at {commit} contained no files")
        # GitHub wraps everything in `<owner>-<repo>-<sha-or-ref>/`.
        prefix = members[0].name.split("/", 1)[0] + "/"
        for member in members:
            if not member.name.startswith(prefix):
                continue
            rel = member.name[len(prefix) :]
            if not rel or rel.endswith("/"):
                continue
            if member.issym():
                records[rel] = f"symlink:{member.linkname}"
            else:
                handle = archive.extractfile(member)
                if handle is None:
                    continue
                with handle:
                    records[rel] = _digest_stream(handle.read)
    return records


# ---------------------------------------------------------------------------
# Diff reporting
# ---------------------------------------------------------------------------


def diff(expected: dict[str, str], actual: dict[str, str]) -> dict[str, list[str]]:
    added = sorted(set(actual) - set(expected))
    removed = sorted(set(expected) - set(actual))
    changed = sorted(p for p in set(expected) & set(actual) if expected[p] != actual[p])
    return {"added": added, "removed": removed, "changed": changed}


def report(label: str, expected: dict[str, str], actual: dict[str, str]) -> bool:
    delta = diff(expected, actual)
    if not any(delta.values()):
        print(f"OK   {label}: {len(actual)} files, digest {aggregate(actual)}")
        return True
    print(f"FAIL {label}: the vendored tree diverged", file=sys.stderr)
    for kind, note in (
        ("added", "files not in the pinned snapshot"),
        ("removed", "files from the pinned snapshot that are gone"),
        ("changed", "files whose contents differ from the pinned snapshot"),
    ):
        paths = delta[kind]
        if not paths:
            continue
        print(f"  {kind} ({len(paths)}) — {note}:", file=sys.stderr)
        for path in paths[:40]:
            print(f"    {path}", file=sys.stderr)
        if len(paths) > 40:
            print(f"    … and {len(paths) - 40} more", file=sys.stderr)
    print(
        "\n  Do not hand-edit anything under packages/craft-launcher. Propose the change\n"
        "  upstream, refresh the snapshot, then run:\n"
        "      python scripts/vendored_manifest.py write --commit <new-sha>\n"
        "  See docs/VENDORED-craft-launcher.md and docs/THIRD_PARTY_POLICY.md (T-3).",
        file=sys.stderr,
    )
    return False


# ---------------------------------------------------------------------------
# Commands
# ---------------------------------------------------------------------------


def cmd_verify(args: argparse.Namespace, root: Path) -> int:
    manifest_path = root / args.manifest
    if not manifest_path.exists():
        print(f"FAIL no manifest at {args.manifest}", file=sys.stderr)
        print("     run: python scripts/vendored_manifest.py write", file=sys.stderr)
        return 1
    manifest = parse(manifest_path)
    ok = True

    actual = collect(root, manifest.tree)
    ok &= report(f"{manifest.tree} vs {args.manifest}", manifest.records, actual)

    if manifest.digest != aggregate(manifest.records):
        print(
            f"FAIL {args.manifest}: aggregate digest {manifest.digest} "
            "does not match its own records",
            file=sys.stderr,
        )
        ok = False

    if manifest.declared_files >= 0 and manifest.declared_files != manifest.files:
        print(
            f"FAIL {args.manifest}: header says files={manifest.declared_files} "
            f"but {manifest.files} records are listed",
            file=sys.stderr,
        )
        ok = False

    stray = untracked_files(root, manifest.tree)
    if stray:
        print(f"WARN {len(stray)} untracked file(s) inside {manifest.tree}:", file=sys.stderr)
        for path in stray[:20]:
            print(f"    {path}", file=sys.stderr)
        print("     a distributed snapshot must not carry local debris.", file=sys.stderr)

    if args.upstream:
        print(f"     fetching {manifest.source} @ {manifest.commit} …")
        upstream = upstream_records(manifest.commit, manifest.tree)
        ok &= report("upstream tarball vs local tree", upstream, actual)

    return 0 if ok else 1


def cmd_write(args: argparse.Namespace, root: Path) -> int:
    tree = args.tree
    if not (root / tree).is_dir():
        print(f"FAIL no such tree: {tree}", file=sys.stderr)
        return 2
    records = collect(root, tree)
    if not records:
        print(
            f"FAIL {tree} has no tracked files — refusing to write an empty manifest",
            file=sys.stderr,
        )
        return 1

    manifest_path = root / args.manifest
    source, commit, version = args.source, args.commit, args.version
    if manifest_path.exists() and not (args.commit or args.source or args.version):
        # Refreshing in place keeps the recorded provenance unless overridden.
        previous = parse(manifest_path)
        source = source or previous.source
        commit = commit or previous.commit
        version = version or previous.version
    source = source or SOURCE
    commit = commit or COMMIT
    version = version or VERSION

    if not re.fullmatch(r"[0-9a-f]{40}", commit):
        print(
            f"FAIL --commit must be a full 40-char sha, got {commit!r}.\n"
            "     A branch name or short sha is not a pin: it can move under us.",
            file=sys.stderr,
        )
        return 2

    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_path.write_text(
        render(records, source=source, commit=commit, version=version, tree=tree),
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote {args.manifest}")
    print(f"  source  {source}")
    print(f"  commit  {commit}")
    print(f"  version {version}")
    print(f"  files   {len(records)}")
    print(f"  digest  {aggregate(records)}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="vendored_manifest.py",
        description="Verify or regenerate the vendored-snapshot integrity manifest.",
    )
    parser.add_argument(
        "--root", type=Path, default=None, help="repository root (default: autodetect)"
    )
    parser.add_argument("--manifest", default=MANIFEST, help=f"manifest path (default: {MANIFEST})")
    parser.add_argument("--tree", default=TREE, help=f"vendored tree (default: {TREE})")
    sub = parser.add_subparsers(dest="command")

    p_verify = sub.add_parser("verify", help="compare the tree against the manifest")
    p_verify.add_argument(
        "--upstream",
        action="store_true",
        help="also fetch the pinned upstream tarball and compare (needs network)",
    )
    p_verify.set_defaults(func=cmd_verify)

    p_write = sub.add_parser("write", help="regenerate the manifest after a deliberate refresh")
    p_write.add_argument("--commit", default=None, help="full 40-char upstream sha being pinned")
    p_write.add_argument("--source", default=None, help="upstream repository URL")
    p_write.add_argument("--version", default=None, help="upstream version string")
    p_write.set_defaults(func=cmd_write)

    args = parser.parse_args(argv)
    if not getattr(args, "func", None):
        args.func = cmd_verify  # bare invocation verifies
        args.upstream = False
    root = args.root.resolve() if args.root else repo_root()
    return args.func(args, root)


if __name__ == "__main__":
    raise SystemExit(main())
